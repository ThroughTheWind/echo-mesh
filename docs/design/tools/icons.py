#!/usr/bin/env python3
"""Build components/icons.svg, the preview icon sprite, from Material Symbols Rounded (Apache-2.0).

  npm pack @material-symbols/svg-500 && tar -xzf material-symbols-svg-500-*.tgz
  python3 tools/icons.py package/rounded

The app uses the same glyphs as vector drawables; previews use this sprite so they make no network
request (Zapper's previews load the icon font from Google; this project's previews must not).
"""
import re
import sys
from pathlib import Path

ICONS = [
    # report types (SPEC FR-4.1)
    "local_police", "fence", "foggy", "person_alert", "block", "medical_services", "water_drop", "door_open",
    "check_circle",
    # map, mesh, groups, safety
    "my_location", "navigation", "layers", "radar", "sensors_off", "sync", "group", "group_add", "person",
    "qr_code_2", "qr_code_scanner", "share_location", "location_off", "check", "close", "delete_forever",
    "warning", "visibility_off", "visibility", "timer", "hourglass_bottom", "lock", "shield", "map",
    "download", "folder_open", "light_mode", "dark_mode", "more_vert", "arrow_back", "add_location_alt",
    "logout", "key", "info", "touch_app", "cancel", "schedule", "near_me", "filter_alt", "settings",
]

def main(src):
    out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
           "<!-- GENERATED by tools/icons.py from Material Symbols Rounded, weight 500, filled. Apache-2.0. -->"]
    for name in ICONS:
        svg = (Path(src) / f"{name}-fill.svg").read_text()
        paths = "".join(re.findall(r"<path[^>]*/>", svg))
        out.append(f'<symbol id="i-{name}" viewBox="0 -960 960 960">{paths}</symbol>')
    out.append("</svg>")
    dest = Path(__file__).resolve().parent.parent / "components" / "icons.svg"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({len(ICONS)} icons)")

if __name__ == "__main__":
    main(sys.argv[1])
